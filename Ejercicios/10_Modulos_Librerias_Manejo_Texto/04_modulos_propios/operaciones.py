def sumar(n1: float, n2: float) -> float:
    return n1 + n2


def restar(n1: float, n2: float) -> float:
    return n1 - n2


def multiplicar(n1: float, n2: float) -> float:
    return n1 * n2


def dividir(n1: float, n2: float) -> float:
    return n1 / n2
