'''
    mostrar si un número es par
'''

numero = 46

if numero % 2 == 0:
    print("Es par")
else: 
    print("Es impar")

'''
    Mostrar si es par y múltiplo de 3
'''

numero = 46

if numero % 2 == 0:
    print("Es par")
else: 
    print("Es impar")

if numero % 3 == 0:
    print("Es múltiplo de 3")
else: 
    print("No es múltiplo de 3")
